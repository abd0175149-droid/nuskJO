<?php

namespace App\Services\WhatsApp;

/**
 * حارس الملاحظة المثبتة (E29): لا رقم جواز ولا هوية ولا بطاقة في نص داخلي يراه كل من يفتح المحادثة.
 * بعد توحيد الأرقام: 9 أرقام متتالية فأكثر، أو نمط جواز (حرف أو حرفان ثم 6–9 أرقام)، أو نمط بطاقة (13–19 رقماً بفواصل).
 * التواريخ والأسعار القصيرة مسموحة، وكذلك أرقام مستنداتنا (QR-20261016-0001، INV-…، CLT-001).
 */
final class NoteGuard
{
    public const MESSAGE = 'لا تكتب أرقام جوازات أو هويات أو بطاقات في الملاحظة المثبتة';

    public static function looksSensitive(string $note): bool
    {
        $t = NumberGuard::latinDigits($note);
        // محارف لا تُرى تفصل الأرقام (U+200B…) لا تُخفي رقماً طويلاً
        $t = preg_replace('/[\x{200B}-\x{200F}\x{2060}\x{FEFF}]/u', '', $t) ?? $t;
        // أرقام مستنداتنا الداخلية ليست بيانات شخصية
        $t = preg_replace('/(?<![A-Za-z])(?:[A-Z]{2,4}-\d{8}-\d{1,6}|CLT-\d{1,8})(?!\d)/i', ' ', $t) ?? $t;

        return (bool) (preg_match('/\d{9,}/', $t)
            || preg_match('/(?<![A-Za-z])[A-Za-z]{1,2}[\s-]?\d{6,9}(?!\d)/', $t)
            || preg_match('/(?<!\d)\d(?:[ -]?\d){12,18}(?!\d)/', $t));
    }
}
